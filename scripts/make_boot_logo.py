#!/usr/bin/env python3
"""Slice assets/rockos-logo-outlined.png into 5 facets + 6 letters and write
src/kernel/boot_logo_data.h (8-bit alpha masks) for the RockOS boot animation.

Needs only Pillow:  pip install pillow
Usage:  python scripts/make_boot_logo.py [logo.png] [out.h]
"""
import os
import sys
from array import array

from PIL import Image, ImageChops, ImageFilter, ImageOps

LOGO_W = 560            # on-screen logo width in pixels (matches the kernel layout)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "assets", "rockos-logo-outlined.png")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "src", "kernel", "boot_logo_data.h")

im = Image.open(src).convert("RGBA")
alpha = im.getchannel("A")
if alpha.getextrema()[0] == 255:            # no transparency: dark ink on white
    alpha = ImageOps.invert(im.convert("L"))
W, H = alpha.size
S = LOGO_W / W
LOGO_H = int(round(H * S))

# --- connected components (4-connected) of the ink, pure Python ---
fg = alpha.point(lambda v: 1 if v > 100 else 0).tobytes()
labels = array("H", bytes(2 * W * H))
boxes = {}
nxt = 0
for start in range(W * H):
    if not fg[start] or labels[start]:
        continue
    nxt += 1
    labels[start] = nxt
    stack = [start]
    x0 = x1 = start % W
    y0 = y1 = start // W
    area = 0
    while stack:
        p = stack.pop()
        area += 1
        y, x = divmod(p, W)
        if x < x0: x0 = x
        if x > x1: x1 = x
        if y < y0: y0 = y
        if y > y1: y1 = y
        for q, ok in ((p - 1, x > 0), (p + 1, x < W - 1), (p - W, y > 0), (p + W, y < H - 1)):
            if ok and fg[q] and not labels[q]:
                labels[q] = nxt
                stack.append(q)
    boxes[nxt] = (x0, y0, x1 + 1, y1 + 1, area)

comps = sorted((b for b in boxes.items() if b[1][4] >= 400), key=lambda b: b[1][0])
if len(comps) != 11:
    sys.exit("expected 11 pieces (5 facets + 6 letters), found %d" % len(comps))

parts = []
for ident, (bx0, by0, bx1, by1, _) in comps:
    x0, y0 = max(0, bx0 - 3), max(0, by0 - 3)
    x1, y1 = min(W, bx1 + 3), min(H, by1 + 3)
    cw, ch = x1 - x0, y1 - y0
    m = bytearray(cw * ch)
    for row in range(ch):
        base = (y0 + row) * W + x0
        seg = labels[base:base + cw]
        for col in range(cw):
            if seg[col] == ident:
                m[row * cw + col] = 255
    mask = Image.frombytes("L", (cw, ch), bytes(m)).filter(ImageFilter.MaxFilter(7))
    piece = ImageChops.multiply(alpha.crop((x0, y0, x1, y1)), mask)   # keeps anti-aliased edges
    w, h = max(1, int(round(cw * S))), max(1, int(round(ch * S)))
    piece = piece.resize((w, h), Image.LANCZOS)
    parts.append((int(round(x0 * S)), int(round(y0 * S)), w, h, piece.tobytes()))

out = ["/* Generated by scripts/make_boot_logo.py - do not edit. */",
       "#ifndef ROCKOS_BOOT_LOGO_DATA_H", "#define ROCKOS_BOOT_LOGO_DATA_H", "",
       "#include <stdint.h>", "",
       "#define BLOGO_W %d" % LOGO_W, "#define BLOGO_H %d" % LOGO_H,
       "#define BLOGO_FLY %d" % int(round(260 * S)),
       "#define BLOGO_FACETS 5", "#define BLOGO_LETTERS 6", "",
       "typedef struct { int16_t x, y; uint16_t w, h; const uint8_t* a; } blogo_part_t;", ""]
for n, (x, y, w, h, data) in enumerate(parts):
    out.append("static const uint8_t blogo_a%d[%d] = {" % (n, len(data)))
    for k in range(0, len(data), 24):
        out.append(" " + ",".join(str(b) for b in data[k:k + 24]) + ",")
    out.append("};")
out.append("")
out.append("/* 0..4 facets (big, left, top, right, bottom), 5..10 letters R o c k O S */")
out.append("static const blogo_part_t blogo_parts[11] = {")
for n, (x, y, w, h, _) in enumerate(parts):
    out.append("    {%d, %d, %d, %d, blogo_a%d}," % (x, y, w, h, n))
out += ["};", "", "#endif", ""]
with open(dst, "w", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", dst, "-", LOGO_W, "x", LOGO_H, "-", sum(len(p[4]) for p in parts), "bytes of masks")
